function RelatedAnimations({ currentAnim }) {
  const [related,  setRelated]  = useState([])
  const [loading,  setLoading]  = useState(true)
  const [visible,  setVisible]  = useState(false)
  const sectionRef = useRef(null)

  useEffect(() => {
    if (!currentAnim?.docId) return
    let cancelled = false

    getAnimations().then(all => {
      if (cancelled) return
      const others = all.filter(a => a.docId !== currentAnim.docId)

      // Score each animation
      const scored = others.map(a => ({
        ...a,
        score: codeSimilarity(currentAnim, a),
      }))

      // Sort by score descending
      scored.sort((a, b) => b.score - a.score)

      // Take top 4 — threshold very low (0.01) to always get results
      // If even that fails, fallback to same category
      let top = scored.filter(a => a.score > 0.01).slice(0, 4)

      if (top.length < 2) {
        // Fallback: same category
        const sameCat = others.filter(a => a.category === currentAnim.category).slice(0, 4)
        if (sameCat.length > 0) {
          top = sameCat.map(a => ({ ...a, score: 0 }))
        } else {
          // Last resort: just take first 4
          top = others.slice(0, 4).map(a => ({ ...a, score: 0 }))
        }
      }

      setRelated(top)
      setLoading(false)

      // Show with a short delay after render
      setTimeout(() => setVisible(true), 100)
    })

    return () => { cancelled = true }
  }, [currentAnim?.docId])

  if (loading || related.length === 0) return null

  return (
    <div
      ref={sectionRef}
      className={`related-section ${visible ? 'related-in' : ''}`}
    >
      <div className="related-header">
        <div className="related-line"/>
        <h2 className="related-title">
          <span className="related-icon">⚡</span>
          Similar Animations
          {related[0]?.score > 0 && <span className="related-badge">By Code</span>}
          {related[0]?.score === 0 && <span className="related-badge related-badge-cat">Same Category</span>}
        </h2>
        <div className="related-line"/>
      </div>

      <div className="related-grid">
        {related.map((anim, i) => (
          <Link
            key={anim.docId}
            to={`/animation/${anim.docId}`}
            className="related-card"
            style={{ animationDelay: `${i * 0.09}s` }}
          >
            <div className="related-preview" style={{ background: anim.previewBg||'#1a1a28' }}>
              <MiniPreview cssCode={anim.cssCode} jsCode={anim.jsCode} bg={anim.previewBg}/>
              {anim.score > 0 && (
                <div className="related-score-badge">{Math.round(anim.score*100)}% match</div>
              )}
            </div>
            <div className="related-info">
              <span className="related-cat">{anim.category}</span>
              <span className="related-name">{anim.title}</span>
            </div>
          </Link>
        ))}
      </div>
    </div>
  )
}

