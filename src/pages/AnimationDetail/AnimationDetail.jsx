// ─── Animated BG ────────────────────────────────────────────
function DetailBg({ hue=260 }) {
  const cvRef = useRef(null)
  useEffect(() => {
    const cv = cvRef.current; if (!cv) return
    const ctx = cv.getContext('2d')
    let id, t = 0
    function resize() { cv.width=cv.offsetWidth||window.innerWidth; cv.height=cv.offsetHeight||window.innerHeight }
    resize()
    window.addEventListener('resize', resize, { passive:true })
    function draw() {
      const W=cv.width, H=cv.height
      ctx.clearRect(0,0,W,H)
      const bx=W*0.3+Math.sin(t*0.4)*W*0.2, by=H*0.3+Math.cos(t*0.3)*H*0.15
      const g1=ctx.createRadialGradient(bx,by,0,bx,by,W*0.45)
      g1.addColorStop(0,`hsla(${hue},70%,45%,0.09)`); g1.addColorStop(1,'transparent')
      ctx.fillStyle=g1; ctx.fillRect(0,0,W,H)
      const bx2=W*0.7+Math.cos(t*0.35)*W*0.18, by2=H*0.65+Math.sin(t*0.28)*H*0.2
      const g2=ctx.createRadialGradient(bx2,by2,0,bx2,by2,W*0.35)
      g2.addColorStop(0,`hsla(${(hue+40)%360},65%,50%,0.07)`); g2.addColorStop(1,'transparent')
      ctx.fillStyle=g2; ctx.fillRect(0,0,W,H)
      t+=0.007; id=requestAnimationFrame(draw)
    }
    draw()
    return () => { cancelAnimationFrame(id); window.removeEventListener('resize',resize) }
  }, [hue])
  return <canvas ref={cvRef} className="detail-bg-canvas"/>
}

