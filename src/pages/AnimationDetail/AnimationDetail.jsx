// Improved token extractor — focuses on DISTINCTIVE tokens
function extractSignature(css='', js='') {
  const sig = new Set()

  // 1. @keyframes names — very distinctive
  const kfNames = css.match(/@keyframes\s+([\w-]+)/g) || []
  kfNames.forEach(k => sig.add(k.replace('@keyframes','').trim()))

  // 2. CSS custom properties (--var-name)
  const cssVars = css.match(/--[\w-]+/g) || []
  cssVars.forEach(v => sig.add(v))

  // 3. Canvas / WebGL calls in JS (specific methods)
  const canvasMethods = js.match(/ctx\.(arc|bezierCurveTo|quadraticCurveTo|lineTo|moveTo|fillRect|strokeRect|createRadialGradient|createLinearGradient|drawImage|fillText|strokeText|createPattern)\b/g) || []
  canvasMethods.forEach(m => sig.add(m))

  // 4. CSS transform functions used
  const transforms = css.match(/(translateX|translateY|translate3d|rotate3d|rotateX|rotateY|scaleX|scaleY|skewX|skewY|perspective)\s*\(/g) || []
  transforms.forEach(t => sig.add(t.replace('(','').trim()))

  // 5. Specific animation properties: timing functions
  const timings = (css+' '+js).match(/(cubic-bezier|spring|elastic|bounce|ease-in-out|steps\(\d)/g) || []
  timings.forEach(t => sig.add(t))

  // 6. JS: distinctive variable names (camelCase, 6+ chars, no generic)
  const SKIP = new Set(['function','return','const','let','var','this','Math','window','document',
    'undefined','null','true','false','length','width','height','canvas','context',
    'requestAnimationFrame','cancelAnimationFrame','addEventListener','appendChild',
    'createElement','querySelectorAll','getElementById','innerHTML','style','forEach'])
  const jsVars = js.match(/\b[a-z][a-zA-Z]{5,}\b/g) || []
  jsVars.forEach(v => { if(!SKIP.has(v)) sig.add(v) })

  // 7. Color patterns (hsl, rgba usage patterns)
  if (css.includes('hsl(') || js.includes('hsl(')) sig.add('__hsl__')
  if (css.includes('rgba(') || js.includes('rgba(')) sig.add('__rgba__')
  if (js.includes('canvas') || js.includes('Canvas')) sig.add('__canvas__')
  if (css.includes('@keyframes')) sig.add('__keyframes__')
  if (js.includes('particle') || js.includes('Particle')) sig.add('__particles__')
  if (js.includes('noise') || js.includes('perlin')) sig.add('__noise__')
  if (css.includes('clip-path')) sig.add('__clippath__')
  if (css.includes('filter:') || css.includes('filter :')) sig.add('__filter__')
  if (js.includes('THREE') || js.includes('three')) sig.add('__three__')
  if (js.includes('gsap') || js.includes('GSAP')) sig.add('__gsap__')
  if (js.includes('svg') || js.includes('SVG')) sig.add('__svg__')

  return sig
}

function codeSimilarity(a, b) {
  const sigA = extractSignature(a.cssCode||'', a.jsCode||'')
  const sigB = extractSignature(b.cssCode||'', b.jsCode||'')
  if (!sigA.size && !sigB.size) return 0
  if (!sigA.size || !sigB.size) return 0
  let common = 0
  sigA.forEach(t => { if (sigB.has(t)) common++ })
  // Jaccard similarity
  const union = new Set([...sigA, ...sigB])
  return common / union.size
}

